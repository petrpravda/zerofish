use super::network::{Accumulator, Layer, Stack, HIDDEN};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kernel {
    Scalar,
    Avx512Vnni,
    /// Stockfish-compatible sparse compaction and independent VNNI chains.
    Avx512SparseVnni,
    /// Stockfish-style exact dirty features and fused accumulator updates.
    Avx512Stockfish,
}
impl Kernel {
    pub fn best() -> Self {
        if Self::avx512_available() {
            Self::Avx512Stockfish
        } else {
            Self::Scalar
        }
    }
    pub fn avx512_available() -> bool {
        #[cfg(target_arch = "x86_64")]
        {
            std::is_x86_feature_detected!("avx512f")
                && std::is_x86_feature_detected!("avx512bw")
                && std::is_x86_feature_detected!("avx512vnni")
                && std::is_x86_feature_detected!("popcnt")
        }
        #[cfg(not(target_arch = "x86_64"))]
        {
            false
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Self::Scalar => "Rust scalar",
            Self::Avx512Vnni => "Rust AVX-512BW/VNNI",
            Self::Avx512SparseVnni => "Rust sparse AVX-512/VNNI",
            Self::Avx512Stockfish => "Rust Stockfish-style AVX-512/VNNI",
        }
    }
    pub(super) fn update(
        self,
        acc: &mut Accumulator,
        weights: &[i8],
        removed: &[u32],
        added: &[u32],
    ) {
        // Nnue accepts public BoardState values. Check the unsafe kernel's
        // row-address contract even if a caller supplies an invalid chess position.
        let rows = weights.len() / HIDDEN;
        assert!(
            removed
                .iter()
                .chain(added)
                .all(|&row| (row as usize) < rows),
            "NNUE feature row outside network"
        );
        #[cfg(target_arch = "x86_64")]
        if self != Self::Scalar {
            // Construction of a SIMD evaluator verifies host support. Every feature
            // index is generated by the checked architecture-specific encoders.
            unsafe {
                if self == Self::Avx512Stockfish {
                    let ptr = acc.as_mut_ptr();
                    x86::update_stockfish(ptr, ptr, weights, removed, added);
                } else {
                    x86::update(acc, weights, removed, added);
                }
            }
            return;
        }
        for &row in removed {
            for (value, &weight) in acc
                .iter_mut()
                .zip(&weights[row as usize * HIDDEN..][..HIDDEN])
            {
                *value = value.wrapping_sub(weight as i16);
            }
        }
        for &row in added {
            for (value, &weight) in acc
                .iter_mut()
                .zip(&weights[row as usize * HIDDEN..][..HIDDEN])
            {
                *value = value.wrapping_add(weight as i16);
            }
        }
    }
    pub(super) fn update_from(
        self,
        source: &Accumulator,
        target: &mut Accumulator,
        weights: &[i8],
        removed: &[u32],
        added: &[u32],
    ) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Stockfish {
            let rows = weights.len() / HIDDEN;
            assert!(
                removed
                    .iter()
                    .chain(added)
                    .all(|&row| (row as usize) < rows),
                "NNUE feature row outside network"
            );
            unsafe {
                x86::update_stockfish(
                    source.as_ptr(),
                    target.as_mut_ptr(),
                    weights,
                    removed,
                    added,
                );
            }
            return;
        }
        *target = *source;
        self.update(target, weights, removed, added);
    }
    pub(super) fn propagate(
        self,
        stack: &Stack,
        accumulators: &[Accumulator; 2],
        stm: usize,
    ) -> i32 {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Stockfish {
            unsafe {
                return x86::propagate(stack, accumulators, stm);
            }
        }
        let mut first = [0; 32];
        self.input_layer(accumulators, stm, &stack.first, &mut first);
        let mut concat = [0; 128];
        self.activate(&first, &mut concat[..64], 7);
        let mut second = [0; 32];
        self.affine(&stack.second, &concat[..64], &mut second);
        self.activate(&second, &mut concat[64..], 6);
        let mut last = [0];
        self.affine(&stack.last, &concat, &mut last);
        last[0] + first[30] - first[31]
    }
    pub(super) fn input_layer(
        self,
        accumulators: &[Accumulator; 2],
        stm: usize,
        layer: &Layer,
        out: &mut [i32; 32],
    ) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Stockfish {
            unsafe {
                x86::fused_input_layer(accumulators, stm, layer, out);
            }
            return;
        }
        let mut input = [0; HIDDEN];
        self.transform(&accumulators[stm], &mut input[..512]);
        self.transform(&accumulators[1 - stm], &mut input[512..]);
        self.affine(layer, &input, out);
    }
    pub(super) fn transform(self, acc: &Accumulator, out: &mut [u8]) {
        #[cfg(target_arch = "x86_64")]
        if self != Self::Scalar {
            unsafe {
                if matches!(self, Self::Avx512SparseVnni | Self::Avx512Stockfish) {
                    x86::transform_sparse(acc, out);
                } else {
                    x86::transform(acc, out);
                }
            }
            return;
        }
        for i in 0..512 {
            out[i] = ((acc[i].clamp(0, 255) as u32 * acc[i + 512].clamp(0, 255) as u32) >> 9) as u8;
        }
    }
    pub(super) fn affine(self, layer: &Layer, input: &[u8], out: &mut [i32]) {
        #[cfg(target_arch = "x86_64")]
        if self != Self::Scalar {
            unsafe {
                if matches!(self, Self::Avx512SparseVnni | Self::Avx512Stockfish)
                    && layer.inputs == HIDDEN
                    && layer.outputs == 32
                {
                    if self == Self::Avx512Stockfish {
                        x86::stockfish_first(layer, input, out);
                    } else {
                        x86::sparse_first(layer, input, out);
                    }
                } else if self == Self::Avx512Stockfish && layer.inputs == 64 && layer.outputs == 32
                {
                    x86::dense_second(layer, input, out);
                } else {
                    x86::affine(layer, input, out);
                }
            }
            return;
        }
        out.copy_from_slice(&layer.biases);
        for (chunk, values) in input.chunks_exact(4).enumerate() {
            if values == [0, 0, 0, 0] {
                continue;
            }
            for (o, value) in out.iter_mut().enumerate() {
                for k in 0..4 {
                    *value += values[k] as i32
                        * layer.weights[chunk * layer.outputs * 4 + o * 4 + k] as i32;
                }
            }
        }
    }
    pub(super) fn activate(self, input: &[i32; 32], out: &mut [u8], shift: i32) {
        #[cfg(target_arch = "x86_64")]
        if self != Self::Scalar {
            unsafe {
                x86::activate(input, out, shift);
            }
            return;
        }
        for i in 0..32 {
            out[i] = (((input[i] as i64 * input[i] as i64) >> (2 * shift + 7)).min(127)) as u8;
            out[i + 32] = (input[i] >> shift).clamp(0, 127) as u8;
        }
    }
}

