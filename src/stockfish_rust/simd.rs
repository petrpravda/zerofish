use super::network::{Accumulator, Layer, HIDDEN};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kernel {
    Scalar,
    Avx512Vnni,
}
impl Kernel {
    pub fn best() -> Self {
        if Self::avx512_available() {
            Self::Avx512Vnni
        } else {
            Self::Scalar
        }
    }
    pub fn avx512_available() -> bool {
        #[cfg(target_arch = "x86_64")]
        {
            std::is_x86_feature_detected!("avx512f")
                && std::is_x86_feature_detected!("avx512bw")
                && std::is_x86_feature_detected!("avx512vnni")
        }
        #[cfg(not(target_arch = "x86_64"))]
        {
            false
        }
    }
    pub fn name(self) -> &'static str {
        match self {
            Self::Scalar => "Rust scalar",
            Self::Avx512Vnni => "Rust AVX-512BW/VNNI",
        }
    }
    pub(super) fn update(
        self,
        acc: &mut Accumulator,
        weights: &[i8],
        removed: &[u32],
        added: &[u32],
    ) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Vnni {
            // Construction of a SIMD evaluator verifies host support. Every feature
            // index is generated by the checked architecture-specific encoders.
            unsafe {
                x86::update(acc, weights, removed, added);
            }
            return;
        }
        for &row in removed {
            for (value, &weight) in acc
                .iter_mut()
                .zip(&weights[row as usize * HIDDEN..][..HIDDEN])
            {
                *value = value.wrapping_sub(weight as i16);
            }
        }
        for &row in added {
            for (value, &weight) in acc
                .iter_mut()
                .zip(&weights[row as usize * HIDDEN..][..HIDDEN])
            {
                *value = value.wrapping_add(weight as i16);
            }
        }
    }
    pub(super) fn transform(self, acc: &Accumulator, out: &mut [u8]) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Vnni {
            unsafe {
                x86::transform(acc, out);
            }
            return;
        }
        for i in 0..512 {
            out[i] = ((acc[i].clamp(0, 255) as u32 * acc[i + 512].clamp(0, 255) as u32) >> 9) as u8;
        }
    }
    pub(super) fn affine(self, layer: &Layer, input: &[u8], out: &mut [i32]) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Vnni {
            unsafe {
                x86::affine(layer, input, out);
            }
            return;
        }
        out.copy_from_slice(&layer.biases);
        for (chunk, values) in input.chunks_exact(4).enumerate() {
            if values == [0, 0, 0, 0] {
                continue;
            }
            for (o, value) in out.iter_mut().enumerate() {
                for k in 0..4 {
                    *value += values[k] as i32
                        * layer.weights[chunk * layer.outputs * 4 + o * 4 + k] as i32;
                }
            }
        }
    }
    pub(super) fn activate(self, input: &[i32; 32], out: &mut [u8], shift: i32) {
        #[cfg(target_arch = "x86_64")]
        if self == Self::Avx512Vnni {
            unsafe {
                x86::activate(input, out, shift);
            }
            return;
        }
        for i in 0..32 {
            out[i] = (((input[i] as i64 * input[i] as i64) >> (2 * shift + 7)).min(127)) as u8;
            out[i + 32] = (input[i] >> shift).clamp(0, 127) as u8;
        }
    }
}

#[cfg(target_arch = "x86_64")]
mod x86 {
    use super::*;
    use std::arch::x86_64::*;
    #[target_feature(enable = "avx512f,avx512bw,avx512vnni")]
    pub unsafe fn update(acc: &mut Accumulator, weights: &[i8], removed: &[u32], added: &[u32]) {
        // Eight accumulator registers per tile keep feature-row loads contiguous
        // while leaving registers for address arithmetic and widening temporaries.
        for base in (0..HIDDEN).step_by(256) {
            let mut values = [_mm512_setzero_si512(); 8];
            for k in 0..8 {
                values[k] = _mm512_loadu_si512(acc.as_ptr().add(base + 32 * k).cast());
            }
            for &feature in removed {
                let row = weights.as_ptr().add(feature as usize * HIDDEN + base);
                for k in 0..8 {
                    values[k] = _mm512_sub_epi16(
                        values[k],
                        _mm512_cvtepi8_epi16(_mm256_loadu_si256(row.add(32 * k).cast())),
                    );
                }
            }
            for &feature in added {
                let row = weights.as_ptr().add(feature as usize * HIDDEN + base);
                for k in 0..8 {
                    values[k] = _mm512_add_epi16(
                        values[k],
                        _mm512_cvtepi8_epi16(_mm256_loadu_si256(row.add(32 * k).cast())),
                    );
                }
            }
            for k in 0..8 {
                _mm512_storeu_si512(acc.as_mut_ptr().add(base + 32 * k).cast(), values[k]);
            }
        }
    }
    #[target_feature(enable = "avx512f,avx512bw,avx512vnni")]
    pub unsafe fn transform(acc: &Accumulator, out: &mut [u8]) {
        let zero = _mm512_setzero_si512();
        let max = _mm512_set1_epi16(255);
        for i in (0..512).step_by(32) {
            let a = _mm512_loadu_si512(acc.as_ptr().add(i).cast());
            let b = _mm512_loadu_si512(acc.as_ptr().add(i + 512).cast());
            let a = _mm512_min_epi16(_mm512_max_epi16(a, zero), max);
            let b = _mm512_min_epi16(_mm512_max_epi16(b, zero), max);
            let product = _mm512_srli_epi16::<9>(_mm512_mullo_epi16(a, b));
            _mm256_storeu_si256(
                out.as_mut_ptr().add(i).cast(),
                _mm512_cvtepi16_epi8(product),
            );
        }
    }
    #[target_feature(enable = "avx512f,avx512bw,avx512vnni")]
    pub unsafe fn affine(layer: &Layer, input: &[u8], out: &mut [i32]) {
        if layer.outputs == 1 {
            // A single output is stored as consecutive groups of four inputs.
            let mut sums = _mm512_setzero_si512();
            for i in (0..layer.inputs).step_by(64) {
                let a = _mm512_loadu_si512(input.as_ptr().add(i).cast());
                let b = _mm512_loadu_si512(layer.weights.as_ptr().add(i).cast());
                sums = _mm512_dpbusd_epi32(sums, a, b);
            }
            out[0] = layer.biases[0] + _mm512_reduce_add_epi32(sums);
            return;
        }
        let mut lo = _mm512_loadu_si512(layer.biases.as_ptr().cast());
        let mut hi = _mm512_loadu_si512(layer.biases.as_ptr().add(16).cast());
        for i in (0..layer.inputs).step_by(4) {
            let four = std::ptr::read_unaligned(input.as_ptr().add(i).cast::<i32>());
            if four == 0 {
                continue;
            }
            let a = _mm512_set1_epi32(four);
            let weights = layer.weights.as_ptr().add(i * 32);
            lo = _mm512_dpbusd_epi32(lo, a, _mm512_loadu_si512(weights.cast()));
            hi = _mm512_dpbusd_epi32(hi, a, _mm512_loadu_si512(weights.add(64).cast()));
        }
        _mm512_storeu_si512(out.as_mut_ptr().cast(), lo);
        _mm512_storeu_si512(out.as_mut_ptr().add(16).cast(), hi);
    }
    #[target_feature(enable = "avx512f,avx512bw,avx512vnni")]
    pub unsafe fn activate(input: &[i32; 32], out: &mut [u8], shift: i32) {
        let zero = _mm512_setzero_si512();
        let max = _mm512_set1_epi32(127);
        for i in [0, 16] {
            let x = _mm512_loadu_si512(input.as_ptr().add(i).cast());
            let clipped = _mm512_min_epi32(
                _mm512_srav_epi32(_mm512_max_epi32(x, zero), _mm512_set1_epi32(shift)),
                max,
            );
            let word = _mm512_min_epi32(
                _mm512_max_epi32(x, _mm512_set1_epi32(-32768)),
                _mm512_set1_epi32(32767),
            );
            let squared = _mm512_min_epi32(
                _mm512_srlv_epi32(
                    _mm512_mullo_epi32(word, word),
                    _mm512_set1_epi32(2 * shift + 7),
                ),
                max,
            );
            _mm_storeu_si128(
                out.as_mut_ptr().add(i).cast(),
                _mm512_cvtepi32_epi8(squared),
            );
            _mm_storeu_si128(
                out.as_mut_ptr().add(i + 32).cast(),
                _mm512_cvtepi32_epi8(clipped),
            );
        }
    }
}
